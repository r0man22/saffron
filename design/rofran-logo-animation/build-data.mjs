// Writes the site's logo files from the traced storyboard (frames.json):
//   app/components/rofran-mark.ts       the finished R (storyboard frame 12): header, footer, fallbacks
//   app/components/rofran-logo-data.ts  the opening threads and the fitted ribbons for the animated mark
//   public/favicon.svg                  the R on the brand burgundy
// Usage: node design/rofran-logo-animation/build-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { FIT_FRAMES, END_FRAME, PARTS, fitAll, distanceField, sampler } from "./ribbons.mjs";

const here = path => fileURLToPath(new URL(path, import.meta.url));
const FRAMES = JSON.parse(readFileSync(here("frames.json"), "utf8"));
const numbers = d => d.match(/-?\d*\.?\d+/g).map(Number);
const compact = d => d.replace(/-?\d*\.?\d+/g, n => String(+(+n).toFixed(1))).replace(/\s+/g, " ").trim();
const bounds = values => {
  const xs = values.filter((_, i) => i % 2 === 0), ys = values.filter((_, i) => i % 2 === 1);
  return [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
};

// Distance fields of the frames the ribbons are fitted to, on a grid of GRID texels per unit.
const GRID = 2.4, PAD = 16;
const [x0, y0, x1, y1] = bounds([...FIT_FRAMES, END_FRAME].flatMap(k => numbers(FRAMES[k].d)));
const minX = x0 - PAD, minY = y0 - PAD, BW = x1 - x0 + PAD * 2, BH = y1 - y0 + PAD * 2;
const W = Math.round(BW * GRID), H = Math.round(BH * GRID);
async function fieldOf(d) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="${minX} ${minY} ${BW} ${BH}" preserveAspectRatio="none"><path d="${d}" fill="#fff"/></svg>`;
  const { data } = await sharp(Buffer.from(svg)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const mask = new Uint8Array(W * H);
  for (let i = 0; i < W * H; i++) mask[i] = data[i * 4 + 3] > 127 ? 1 : 0;
  return sampler(distanceField(mask, W, H), W, H, minX, minY, GRID);
}
const fitted = fitAll(await Promise.all(FIT_FRAMES.map(k => fieldOf(FRAMES[k].d))));
const ribbons = fitted.map(frame => PARTS.map(part => frame[part].map(p => p.map(v => +v.toFixed(2)))));

// The finished R and its box.
const mark = compact(FRAMES[END_FRAME].d), start = compact(FRAMES[FIT_FRAMES[0]].d);
const [mx0, my0, mx1, my1] = bounds(numbers(mark));
const markBox = [mx0 - 1, my0 - 1, mx1 - mx0 + 2, my1 - my0 + 2].map(v => +v.toFixed(1));
// One box around every frame of the motion, with room for the bevel blur.
const ribbonExtent = ribbons.flat(2).flatMap(([x, y, w]) => [x - w / 2, y - w / 2, x + w / 2, y + w / 2]);
const [bx0, by0, bx1, by1] = bounds([...numbers(start), ...numbers(mark), ...ribbonExtent]);
const box = [bx0 - 6, by0 - 6, bx1 - bx0 + 12, by1 - by0 + 12].map(v => +v.toFixed(1));

const header = "// Generated by design/rofran-logo-animation/build-data.mjs from the traced storyboard. Do not edit by hand.\n";
writeFileSync(here("../../app/components/rofran-mark.ts"), `${header}// The finished R monogram (storyboard frame 12), in the storyboard's own coordinate units.
export const MARK_VIEWBOX = "${markBox.join(" ")}";
export const MARK_PATH = "${mark}";
// Box [x, y, width, height] around every frame of the animated mark (threads to R).
export const MOTION_BOX = [${box.join(", ")}] as const;
`);
writeFileSync(here("../../app/components/rofran-logo-data.ts"), `${header}// Storyboard frame 01, the three saffron threads, exactly as traced.
export const LOGO_START = "${start}";
// Ribbons fitted to storyboard frames 01-07. Per frame: stem, leg, inner thread, bowl; each point is [x, y, width].
export const LOGO_RIBBONS: number[][][][] = ${JSON.stringify(ribbons)};
`);
const s = 46 / Math.max(markBox[2], markBox[3]);
const tx = (64 - markBox[2] * s) / 2 - markBox[0] * s, ty = (64 - markBox[3] * s) / 2 - markBox[1] * s;
writeFileSync(here("../../public/favicon.svg"), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="12" fill="#241416"/><path fill="#e5d4a4" transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)}) scale(${s.toFixed(4)})" d="${mark}"/></svg>\n`);
console.log(`mark ${mark.length} chars, start ${start.length} chars, ${ribbons.length} ribbon frames, box ${box.join(" ")}`);
